// Expo config plugin: narrow expo-sharing's FileProvider to `cacheDir/share`, so full-size captures
// in `filesDir` can never be shared through a grant. Checked by `scripts/check-prebuild.ts`.

const { withDangerousMod } = require("expo/config-plugins");
const { promises: fs } = require("fs");
const path = require("path");

/** The one root the provider may address. Byte-for-byte what the gate expects. */
const PATHS_XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
  @generated by plugins/withSharingProviderPaths.js — do not edit by hand.
  Overrides expo-sharing's own resource: only the derivatives in cacheDir/share can be shared.
-->
<paths>
  <cache-path name="cached_expo_files" path="share/" />
</paths>
`;

/** Relative to `android/`. Exported so the gate and the plugin cannot disagree about the path. */
const RELATIVE_PATH = "app/src/main/res/xml/sharing_provider_paths.xml";

const withSharingProviderPaths = (config) =>
  withDangerousMod(config, [
    "android",
    async (config) => {
      const file = path.join(config.modRequest.platformProjectRoot, ...RELATIVE_PATH.split("/"));
      await fs.mkdir(path.dirname(file), { recursive: true });
      await fs.writeFile(file, PATHS_XML, "utf8");
      return config;
    },
  ]);

module.exports = withSharingProviderPaths;
module.exports.PATHS_XML = PATHS_XML;
module.exports.RELATIVE_PATH = RELATIVE_PATH;
