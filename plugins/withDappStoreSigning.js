// Expo config plugin: sign release builds with the dApp Store upload key instead of the template's
// debug key, and refuse to package a release without it. Idempotent; every anchor is asserted.

const { withAppBuildGradle, withGradleProperties } = require("expo/config-plugins");

const MARKER = "// @generated by plugins/withDappStoreSigning.js — do not edit by hand";

const PROPS_DEF = `
${MARKER}
// The dApp Store upload key. Its four values live in ~/.gradle/gradle.properties, never in a repo.
def SEEDSHOT_UPLOAD_PROPS = [
    'SEEDSHOT_UPLOAD_STORE_FILE',
    'SEEDSHOT_UPLOAD_KEY_ALIAS',
    'SEEDSHOT_UPLOAD_STORE_PASSWORD',
    'SEEDSHOT_UPLOAD_KEY_PASSWORD',
]
def seedshotUploadKeyMissing = SEEDSHOT_UPLOAD_PROPS.findAll { !project.hasProperty(it) }
`;

const TEMPLATE_SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

const SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        // Only when this machine has the upload key; a release without it has no fallback.
        if (seedshotUploadKeyMissing.isEmpty()) {
            release {
                storeFile file(findProperty('SEEDSHOT_UPLOAD_STORE_FILE'))
                storePassword findProperty('SEEDSHOT_UPLOAD_STORE_PASSWORD')
                keyAlias findProperty('SEEDSHOT_UPLOAD_KEY_ALIAS')
                keyPassword findProperty('SEEDSHOT_UPLOAD_KEY_PASSWORD')
            }
        }
    }`;

const TEMPLATE_RELEASE_SIGNING = `        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug
`;

const RELEASE_SIGNING = `        release {
            // Never signingConfigs.debug: debug.keystore is public and the dApp Store rejects it.
            if (seedshotUploadKeyMissing.isEmpty()) {
                signingConfig signingConfigs.release
            }
`;

const GUARD = `
// No release APK or AAB without the upload key. Checked at packaging, so debug builds still work.
tasks.matching { it.name == 'packageRelease' || it.name == 'packageReleaseBundle' }.configureEach {
    doFirst {
        if (!seedshotUploadKeyMissing.isEmpty()) {
            throw new GradleException("""
Signshot release build REFUSED: the dApp Store upload key is not configured.

  Missing Gradle propert\${seedshotUploadKeyMissing.size() == 1 ? 'y' : 'ies'}: \${seedshotUploadKeyMissing.join(', ')}

All four are required, and all four belong in ~/.gradle/gradle.properties -- never in this repo:

  SEEDSHOT_UPLOAD_STORE_FILE       absolute path to seedshot-dappstore.keystore
  SEEDSHOT_UPLOAD_KEY_ALIAS        erashot
  SEEDSHOT_UPLOAD_STORE_PASSWORD
  SEEDSHOT_UPLOAD_KEY_PASSWORD

See ~/.seedshot/seedshot-dappstore.README.txt. This build does NOT fall back to
android/app/debug.keystore: that key is committed to this repository, and the Solana dApp Store
rejects debug-signed APKs (docs.solanamobile.com/dapp-store/build-and-sign-an-apk).
""")
        }
    }
}
`;

/** Replace exactly one occurrence, or explain which anchor the template no longer has. */
function replaceOnce(contents, anchor, replacement, what) {
  const first = contents.indexOf(anchor);
  if (first < 0 || contents.indexOf(anchor, first + 1) >= 0) {
    throw new Error(
      `withDappStoreSigning: expected exactly one ${what} in android/app/build.gradle. ` +
        `The Expo template has changed shape; update plugins/withDappStoreSigning.js to match it ` +
        `rather than shipping a release variant that signs with the debug keystore.`,
    );
  }
  return contents.slice(0, first) + replacement + contents.slice(first + anchor.length);
}

function applySigning(contents) {
  if (contents.includes(MARKER)) return contents; // already applied — a sync, not a --clean

  // 1. The property list, right before `android {` (after the template's jscFlavor line).
  let out = replaceOnce(contents, "\nandroid {\n", `${PROPS_DEF}\nandroid {\n`, "`android {` block");
  // 2. The release signing config beside the template's debug one.
  out = replaceOnce(out, TEMPLATE_SIGNING_CONFIGS, SIGNING_CONFIGS, "template signingConfigs block");
  // 3. The release build type signs with the upload key, not the debug key.
  out = replaceOnce(out, TEMPLATE_RELEASE_SIGNING, RELEASE_SIGNING, "template release signingConfig line");
  // 4. The guard, appended at the end of the file.
  return out.replace(/\s*$/, "\n") + GUARD;
}

/** Local build ABIs: the Seeker and an x86_64 emulator. Store builds pass arm64-v8a only. */
const ARCHITECTURES = "arm64-v8a,x86_64";

function applyArchitectures(props) {
  const item = props.find((p) => p.type === "property" && p.key === "reactNativeArchitectures");
  if (item) item.value = ARCHITECTURES;
  else props.push({ type: "property", key: "reactNativeArchitectures", value: ARCHITECTURES });
  return props;
}

const withDappStoreSigning = (config) => {
  config = withAppBuildGradle(config, (c) => {
    if (c.modResults.language !== "groovy") {
      throw new Error("withDappStoreSigning: android/app/build.gradle is not Groovy; this plugin only knows the Groovy template.");
    }
    c.modResults.contents = applySigning(c.modResults.contents);
    return c;
  });
  config = withGradleProperties(config, (c) => {
    c.modResults = applyArchitectures(c.modResults);
    return c;
  });
  return config;
};

module.exports = withDappStoreSigning;
// Exported for scripts/check-signing.ts.
module.exports.applySigning = applySigning;
module.exports.applyArchitectures = applyArchitectures;
module.exports.MARKER = MARKER;
module.exports.WRITTEN_BLOCKS = [PROPS_DEF, SIGNING_CONFIGS, RELEASE_SIGNING, GUARD];
module.exports.TEMPLATE_RELEASE_SIGNING = TEMPLATE_RELEASE_SIGNING;
